STRATEGY_MARKDOWN = """
### 一条策略编码长什么样

像 `S1+P1-2+M2` 这样的写法，其实是几个"零件"用加号拼起来，位置有讲究：

```text
[默认槽] + [触发槽1] + [触发槽2] + [修正槽]
```

- **默认槽**：没有特殊情况时，我出什么牌；
- **触发槽**：遇到某种情况时，我临时改成出什么牌（最多两个）；
- **修正槽**：给前面的判断"戴一副眼镜"，比如只看最近几轮，或者加一点随机。

后面的零件可以覆盖前面的零件，但**只有真的被触发的零件才有这个权力**。所有零件加起来最多四个。

---

### 默认模块（平时怎么出牌）

- **S（先硬后软）** `S{N}`：前 N 轮先背叛，给对方一个下马威，之后一直合作。
  `S0` 是永远合作，`SM` 是永远背叛。
- **F（好人循环）** `F{N}-{M}`：先连续合作 N 轮、再连续背叛 M 轮，如此循环。
  像"平时和气，偶尔耍一次赖"。
- **T（恶人循环）** `T{N}-{M}`：先连续背叛 N 轮、再连续合作 M 轮，如此循环。
  像"先亮拳头，再递橄榄枝"。
- **D（随大流）** `D{N}`：数一数对手历史上合作多还是背叛多，就跟着做。
  参数 0/1 表示"打平时默认合作还是背叛"。
- **AD（唱反调）** `AD{N}`：和 D 相反，对手历史上什么多，我偏不做什么。
- **W（赢就留，输就换）** `W`：上一回合双方都合作，就继续保持；否则翻转自己上一回合的动作。
  首回合合作。
- **BS（最后捅刀）** `BS{N}`：前面一直合作，到对局的最后 N 轮突然背叛，捞一笔就走。

---

### 触发模块（什么时候变脸）

- **P（忍无可忍）** `P{A}-{B}`：默默记下"我合作、对手却背叛"的次数，攒够 A 次就翻脸，
  连续背叛 B 轮，然后重新计数。
- **H（得寸进尺）** `H{A}-{B}`：记下"我背叛、对手却没报复"的次数，攒够 A 次后连续背叛 B 轮。
- **R（奉陪到底）** `R{A}-{B}`：只要对手最近 A 轮一直在背叛，我就连续背叛 B 轮。
- **B（不打不相识）** `B{A}-{B}`：如果双方最近 A 轮都在互相背叛，就主动示好、连续合作 B 轮。
  如果对方在求和期间回以合作，就进入"以牙还牙"的长期状态；如果对方趁机偷袭，也会立刻转为记仇。
- **K（你友善我也友善）** `K{A}-{B}`：对手最近连续 A 轮都在合作，我就连续合作 B 轮。
- **RC（看到回头就原谅）** `RC{A}-{B}`：在最近几轮里寻找对手"从背叛转为合作"（D→C）的迹象，
  一旦发现就原谅，并连续合作 B 轮。

---

### 修正模块（给判断加一层滤镜）

- **M（只看最近）** `M{N}`：让前面所有需要"看历史"的零件只看最近 N 轮，更久远的事不算数。
- **C（手滑概率）** `C{N}`：以 N×10% 的概率把要出的牌翻成相反的一张。
  `C{N}-D` 表示只有合作可能翻成背叛，`C{N}-C` 反之。
- **RPT（自我反省）** `RPT{A}-{B}`：如果自己最近 A 轮里出过背叛，就强制自己合作 B 轮。
  期间只要对手背叛一次，就立刻取消原谅、恢复原样。

---

### 两个"最高优先级"状态

1. **B 求和成功后的以牙还牙**：对方一旦在求和期间回以合作，之后就一直模仿对方。
2. **RPT 原谅状态**：处于自我反省期时，忽略其他所有零件。

这两个状态优先级最高，但只影响当前这一场对局；遇到新对手就恢复成原本的编码。

### 参数 M 的三种含义

- 作为**输出参数**（如 `P1-M`）：从触发那一刻起，一直持续到本局结束；
- 作为**检测参数**（如 `RPTM-1`）：指"本局所有已经完成的回合"；
- 作为**修正模块**（如 `M3`）：本回合只重新统计最近 3 个已完成回合。
"""


